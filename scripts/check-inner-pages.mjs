import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
const base = 'http://127.0.0.1:4175';
const report = [];
const pass = s => { report.push(s); console.log('PASS', s); };
const server = spawn(process.execPath, ['scripts/preview.mjs'], { env: { ...process.env, PORT: '4175' }, windowsHide: true, stdio: ['ignore', 'pipe', 'inherit'] });
let browser;
try {
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); });
    await mkdir('test-results/inner', { recursive: true });
    browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
    await context.addInitScript(() => { window.drafts = []; window.open = (...args) => { window.drafts.push(args); return null; }; });
    let external = 0;
    await context.route('**/*', route => { if (new URL(route.request().url()).origin !== new URL(base).origin) {
        external++;
        return route.abort();
    } return route.continue(); });
    const page = await context.newPage();
    for (const width of [1440, 768, 390, 320]) {
        await page.setViewportSize({ width, height: 900 });
        await page.goto(base + '/contact/');
        await page.waitForTimeout(300);
        const tab = page.getByRole('tab');
        await tab.first().focus();
        await page.keyboard.press('ArrowRight');
        assert.equal(await tab.nth(1).getAttribute('aria-selected'), 'true');
        await page.keyboard.press('End');
        assert.equal(await tab.nth(2).getAttribute('aria-selected'), 'true');
        await page.keyboard.press('Home');
        const submit = () => page.locator('[role="tabpanel"]:visible button[type="submit"]');
        await submit().click();
        assert.equal(await page.evaluate(() => document.activeElement.id), 'enquiry-0-name');
        await page.locator('#enquiry-0-name').fill('  Test & Review  ');
        await page.locator('#enquiry-0-phone').fill('077 123 4567');
        await page.locator('#enquiry-0-email').fill('invalid');
        await submit().click();
        assert.equal(await page.evaluate(() => document.activeElement.id), 'enquiry-0-email');
        await page.locator('#enquiry-0-email').fill('test@example.com');
        await page.locator('#enquiry-0-message').fill('A & B\nCheck + details?');
        await tab.nth(1).click();
        await tab.first().click();
        assert.equal(await page.locator('#enquiry-0-message').inputValue(), 'A & B\nCheck + details?');
        await submit().click();
        const args = await page.evaluate(() => window.drafts.at(-1));
        const url = new URL(args[0]);
        assert.equal(url.pathname, '/94786620728');
        assert.ok(url.searchParams.get('text').includes('Test & Review'));
        assert.ok(url.searchParams.get('text').includes('A & B\nCheck + details?'));
        assert.equal(args[1], '_blank');
        assert.equal(args[2], 'noopener,noreferrer');
        assert.equal(await page.locator('#enquiry-0-name').inputValue(), '');
        assert.equal(await page.locator('.enquiry-status').evaluate(e => e === document.activeElement), true);
        assert.match(await page.locator('.enquiry-status').textContent(), /Nothing has been sent/);
        assert.equal(await page.locator('.enquiry-status a').getAttribute('href'), args[0]);
        await page.screenshot({ path: `test-results/inner/contact-draft-${width}.png`, fullPage: true });
        await tab.nth(1).click();
        await page.locator('#enquiry-1-name').fill('Test');
        await page.locator('#enquiry-1-phone').fill('077 123 4567');
        await submit().click();
        assert.equal(await page.evaluate(() => document.activeElement.id), 'enquiry-1-problem');
        await page.locator('#enquiry-1-problem').fill('   ');
        await submit().click();
        assert.equal(await page.evaluate(() => document.activeElement.id), 'enquiry-1-problem');
        await page.locator('#enquiry-1-problem').fill('Computer does not start');
        await submit().click();
        assert.ok((await page.evaluate(() => window.drafts.at(-1)[0])).includes('Computer%20does%20not%20start'));
        await tab.nth(2).click();
        await page.locator('#enquiry-2-name').fill('Test');
        await page.locator('#enquiry-2-phone').fill('077 123 4567');
        await page.locator('#enquiry-2-quantity').fill('0');
        await submit().click();
        assert.equal(await page.evaluate(() => document.activeElement.id), 'enquiry-2-quantity');
        await page.locator('#enquiry-2-quantity').fill('4');
        await submit().click();
        assert.ok((await page.evaluate(() => window.drafts.at(-1)[0])).includes('Number%20of%20devices%3A%204'));
        await page.locator('.evidence-faq summary').first().focus();
        await page.keyboard.press('Enter');
        await page.locator('.evidence-faq summary').nth(1).click();
        assert.equal(await page.locator('.evidence-faq details[open]').count(), 2);
        await page.screenshot({ path: `test-results/inner/contact-active-${width}.png`, fullPage: true });
        for (const route of ['about', 'support']) {
            await page.goto(`${base}/${route}/`);
            await page.waitForTimeout(150);
            const count = route === 'about' ? 5 : 8;
            assert.equal(await page.locator('.evidence-dots button').count(), count);
            await page.locator('.evidence-prev').click();
            await page.waitForFunction(() => document.querySelector('.evidence-dots button:last-child')?.getAttribute('aria-pressed') === 'true');
            await page.locator('.evidence-next').click();
            await page.waitForFunction(() => document.querySelector('.evidence-dots button')?.getAttribute('aria-pressed') === 'true');
            await page.locator('.evidence-dots button').nth(2).hover();
            await page.waitForFunction(() => document.querySelector('.evidence-dots button')?.getAttribute('aria-pressed') === 'true');
            await page.locator('.evidence-dots button').nth(2).focus();
            await page.keyboard.press('Enter');
            await page.waitForFunction(() => document.querySelectorAll('.evidence-dots button')[2]?.getAttribute('aria-pressed') === 'true');
            if (route === 'support')
                assert.equal(await page.locator('.evidence-slides img').count(), 3);
            await page.screenshot({ path: `test-results/inner/${route}-gallery-active-${width}.png`, fullPage: true });
        }
        await page.goto(base + '/projects/');
        const disclosure = page.locator('.concept-details').first();
        await disclosure.locator('summary').focus();
        await page.keyboard.press('Enter');
        assert.equal(await disclosure.getAttribute('open'), '');
        await page.keyboard.press('Escape');
        assert.equal(await disclosure.getAttribute('open'), null);
        pass(`${width}px: three form tabs/keyboard/state, required/whitespace/email/number validity and focus, encoded drafts/reset/fallback, independent FAQ, gallery selection/wrap/no hover selection, concept disclosure Escape`);
    }
    assert.equal(external, 0);
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    await context.close();
    pass('No messages sent, external requests or form data stored');
    const motion = await browser.newContext({ viewport: { width: 1440, height: 900 } });
    await motion.addInitScript(() => { window.reveals = []; const animate = Element.prototype.animate; Element.prototype.animate = function (frames, options) { if (this.matches('[data-reveal]'))
        window.reveals.push({ frames, options }); return animate.call(this, frames, options); }; });
    const mp = await motion.newPage();
    for (const route of ['about', 'support']) {
        await mp.goto(`${base}/${route}/`);
        await mp.locator('.evidence-carousel').scrollIntoViewIfNeeded();
        await mp.mouse.move(1, 1);
        const active = () => mp.locator('.evidence-dots button[aria-pressed="true"]').getAttribute('aria-label');
        const initial = await active();
        await mp.waitForTimeout(5200);
        assert.notEqual(await active(), initial);
        await mp.locator('.evidence-carousel').hover();
        const paused = await active();
        await mp.waitForTimeout(5200);
        assert.equal(await active(), paused);
        await mp.locator('.evidence-dots button').first().click();
        await mp.waitForTimeout(5200);
        assert.equal(await mp.locator('.evidence-dots button').nth(1).getAttribute('aria-pressed'), 'true');
        await mp.emulateMedia({ reducedMotion: 'reduce' });
        const reduced = await active();
        await mp.waitForTimeout(5200);
        assert.equal(await active(), reduced);
        await mp.emulateMedia({ reducedMotion: 'no-preference' });
        const reveals = await mp.evaluate(() => window.reveals);
        assert.ok(reveals.some(r => r.options.duration === 700 && r.frames[0].transform === 'translateY(22px)'));
        pass(`${route}: 5000ms gallery autoplay, hover pause, manual timer restart while hovered, reduced-motion stop, 22px/700ms reveals`);
    }
    await motion.close();
    await writeFile('test-results/inner-checks.txt', report.join('\n'));
}
finally {
    await browser?.close();
    server.kill();
}
